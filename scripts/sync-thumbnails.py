"""Mirror public product thumbnails into assets/products/opt as light WebP copies.

Supabase's free plan allows 5 GB of cached egress a month; serving every product
image from Storage exceeded it. The storefront prefers a copy listed in
thumbnail-manifest.mjs, so each image is downloaded from Storage once here and
afterwards served by GitHub Pages.

Usage: node scripts/list-public-thumbnails.mjs > paths.txt && python3 scripts/sync-thumbnails.py paths.txt
Existing copies are kept; only new paths are downloaded.
"""
import io, json, re, sys, urllib.request
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'assets/products/opt'
MANIFEST = ROOT / 'thumbnail-manifest.mjs'
BASE = 'https://wlrwlqchlxehlvkyesnj.supabase.co/storage/v1/object/public/storefront-thumbnails/'
PATH_RE = re.compile(r'^[0-9a-f-]{36}/[0-9a-f-]{36}-thumb\.(webp|png)$', re.I)
MAX_SIDE, LIMIT = 720, 150 * 1024

def existing():
    text = MANIFEST.read_text(encoding='utf8')
    return dict(re.findall(r'"([^"]+)":"([^"]+)"', text))

def convert(data):
    im = Image.open(io.BytesIO(data))
    im = im.convert('RGBA') if im.mode in ('P', 'LA', 'RGBA') else im.convert('RGB')
    im.thumbnail((MAX_SIDE, MAX_SIDE), Image.LANCZOS)
    for quality in (80, 70, 60, 50):
        buf = io.BytesIO(); im.save(buf, 'WEBP', quality=quality, method=6)
        if buf.tell() < LIMIT: return buf.getvalue()
    im.thumbnail((540, 540), Image.LANCZOS)
    buf = io.BytesIO(); im.save(buf, 'WEBP', quality=60, method=6)
    return buf.getvalue()

def main(list_file):
    mapping = existing()
    paths = [p.strip() for p in Path(list_file).read_text(encoding='utf8').splitlines() if PATH_RE.match(p.strip())]
    added = 0
    OUT.mkdir(parents=True, exist_ok=True)
    for path in paths:
        target = 'assets/products/opt/' + path.replace('/', '-').rsplit('-thumb.', 1)[0] + '.webp'
        if mapping.get(path) == target and (ROOT / target).exists(): continue
        with urllib.request.urlopen(BASE + path, timeout=60) as r: data = r.read()
        (ROOT / target).write_bytes(convert(data))
        mapping[path] = target; added += 1
    live = set(paths)
    # First-party assets (assets/products/...) are kept; Storage copies are kept only while the product shows them.
    mapping = {k: v for k, v in mapping.items() if (k in live or not PATH_RE.match(k)) and (ROOT / v).exists()} if live else mapping
    header = ('// Lightweight WebP copies (max 720px) of the public product thumbnails, served by GitHub Pages.\n'
              '// Regenerated by scripts/sync-thumbnails.py (daily job). A product whose image is replaced in the admin\n'
              '// gets a new storage path, so it falls back to Storage until the next sync and never shows a stale copy.\n')
    body = ',\n'.join(f' {json.dumps(k)}:{json.dumps(v)}' for k, v in sorted(mapping.items()))
    MANIFEST.write_text(header + 'export const OPTIMIZED_THUMBNAILS={\n' + body + '\n};\n', encoding='utf8')
    print(f'thumbnails: {len(mapping)} mirrored, {added} new')

if __name__ == '__main__':
    main(sys.argv[1])
